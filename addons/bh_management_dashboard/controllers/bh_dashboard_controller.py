# -*- coding: utf-8 -*-
import logging
from datetime import datetime, timedelta

from odoo import http
from odoo.exceptions import AccessDenied
from odoo.http import request

_logger = logging.getLogger(__name__)

# This is Full Controller for Dashboard

class BhDashboardController(http.Controller):

    # ── existing web (session-cookie) endpoint — used by the Odoo backend UI ──
    @http.route('/bh_dashboard/get_data', type='json', auth='user', methods=['POST'])
    def get_dashboard_data(self, date_from=None, date_to=None, **kwargs):
        dashboard = request.env['bh.management.dashboard']
        data = dashboard.get_dashboard_data(date_from=date_from, date_to=date_to)
        return data

    # ── mobile endpoints — authenticated via an Odoo "API Key" header ──
    # Generated by each user under: Settings > Users & Companies > Users >
    # (open user) > Account Security tab > New API Key.
    def _authenticate_api_key(self):
        """Resolve the calling user from the 'API-KEY' header.
        Returns uid (int) or None if missing/invalid."""
        api_key = request.httprequest.headers.get('API-KEY')
        if not api_key:
            return None
        try:
            uid = request.env['res.users.apikeys']._check_credentials(
                scope='rpc', key=api_key
            )
            return uid
        except Exception:
            return None

    def _check_executive_access(self, uid):
        user = request.env['res.users'].sudo().browse(uid)
        return user.has_group('bh_management_dashboard.group_bh_executive') \
            or user.has_group('base.group_system')

    @http.route('/bh_dashboard/mobile/whoami', type='json', auth='public', csrf=False, methods=['POST'])
    def mobile_whoami(self, **kwargs):
        """Lets the app verify the API key + check executive access right
        after login, before showing the dashboard."""
        uid = self._authenticate_api_key()
        if not uid:
            return {'error': 'invalid_api_key'}

        user = request.env['res.users'].sudo().browse(uid)
        return {
            'uid': uid,
            'name': user.name,
            'login': user.login,
            'is_executive': self._check_executive_access(uid),
        }

    # ── email + password login — used by the mobile app's Sign In screen ──
    # Managers never see an API key or server URL: this endpoint verifies
    # their Odoo email/password once, then silently mints (or renews) an
    # API key for them and hands it back. The app stores that key and uses
    # it for every subsequent /mobile/whoami and /mobile/get_data call,
    # exactly as before.
    @http.route('/bh_dashboard/mobile/login', type='json', auth='public', csrf=False, methods=['POST'])
    def mobile_login(self, login=None, password=None, db=None, **kwargs):
        if not login or not password:
            return {'error': 'missing_credentials'}

        dbname = db or request.env.cr.dbname

        uid = None
        try:
            # Odoo 17+ signature: authenticate(dbname, credential_dict)
            credential = {'login': login, 'password': password, 'type': 'password'}
            auth_info = request.session.authenticate(dbname, credential)
            uid = auth_info['uid'] if isinstance(auth_info, dict) else request.session.uid
        except AccessDenied:
            return {'error': 'invalid_credentials'}
        except TypeError:
            # Fallback for older signature: authenticate(dbname, login, password)
            try:
                uid = request.session.authenticate(dbname, login, password)
            except AccessDenied:
                return {'error': 'invalid_credentials'}
        except Exception:
            _logger.exception('BH Dashboard mobile login failed')
            return {'error': 'login_failed'}

        if not uid:
            return {'error': 'invalid_credentials'}

        if not self._check_executive_access(uid):
            return {'error': 'access_denied'}

        user = request.env['res.users'].sudo().browse(uid)

        api_key = None
        last_error = None
        try:
            # Replace any previous mobile key for this user so old ones don't
            # pile up in Settings > Users > Account Security every login.
            request.env['res.users.apikeys'].sudo().search([
                ('user_id', '=', uid),
                ('name', '=', 'Mobile Dashboard App'),
            ]).unlink()
        except Exception:
            _logger.exception('BH Dashboard: could not clear old mobile keys for uid %s', uid)

        # Odoo checks a normal (non-admin) user's key expiry against the
        # longest "API Keys Maximum Duration" of their groups, and that check
        # compares datetimes - so we must pass a real datetime (not a date),
        # slightly under the limit. Admins skip the check, which is why the
        # old date-based call worked for them but failed for managers.
        # Try the longest first, then fall back so login never breaks just
        # because a user's groups allow a shorter key.
        for days in (364, 89, 29, 6):
            try:
                with request.env.cr.savepoint():
                    api_key = request.env['res.users.apikeys'].with_user(uid)._generate(
                        scope='rpc',
                        name='Mobile Dashboard App',
                        expiration_date=datetime.now() + timedelta(days=days),
                    )
                break
            except Exception as exc:
                last_error = exc
                _logger.warning(
                    'BH Dashboard: API key (%s days) refused for uid %s: %s',
                    days, uid, exc)

        if not api_key:
            _logger.error('BH Dashboard: failed to generate mobile API key for uid %s: %r',
                          uid, last_error)
            return {'error': 'key_generation_failed'}

        return {
            'uid': uid,
            'name': user.name,
            'login': user.login,
            'is_executive': True,
            'api_key': api_key,
        }

    @http.route('/bh_dashboard/mobile/get_data', type='json', auth='public', csrf=False, methods=['POST'])
    def mobile_get_dashboard_data(self, date_from=None, date_to=None, **kwargs):
        uid = self._authenticate_api_key()
        if not uid:
            return {'error': 'invalid_api_key'}

        if not self._check_executive_access(uid):
            return {'error': 'access_denied'}

        dashboard = request.env['bh.management.dashboard'].with_user(uid)
        data = dashboard.get_dashboard_data(date_from=date_from, date_to=date_to)
        return data

    